"""Encryption of the data at rest: the database (SQLCipher) and the stored files (pictures, voice-over audio).

One master key, DATA_KEY in deploy/.env (32 random bytes, base64), generated by install.sh / update.sh. Separate
keys for the database and for files are derived from it (HKDF-SHA256), so neither is used for two purposes.
Files are sealed with AES-256-GCM: tampering is detected, and the name of the file is bound to its content, so
one stored file can not be passed off as another.

What it protects: copies of the data directory or of the backups that end up somewhere without deploy/.env
(a downloaded backup, a leaked disk snapshot of the data volume, another user of the machine). It does not stop
someone who controls the running server: they can read deploy/.env too. That is why the key must be kept
somewhere else as well (a password manager): without it neither the data nor the backups can be read.

Without DATA_KEY (tests, local development) everything is stored as before, unencrypted. Data written before the
key was set is still read, and is encrypted once in place (see migrate_files and db.Database)."""
from __future__ import annotations

import base64
import logging
import os

from . import config

log = logging.getLogger("fonar.crypto")

MAGIC = b"GSE1"  # sealed file: MAGIC | 12-byte nonce | AES-256-GCM ciphertext with its 16-byte tag
_NONCE = 12


class DataKeyError(RuntimeError):
    pass


def _master() -> bytes | None:
    raw = (config.settings.data_key or "").strip()
    if not raw:
        return None
    try:
        key = base64.urlsafe_b64decode(raw + "=" * (-len(raw) % 4))
    except (ValueError, TypeError):
        key = b""
    if len(key) != 32:
        raise DataKeyError("DATA_KEY must be 32 random bytes in base64 (deploy/.env); the server does not start without a valid key")
    return key


def _derive(info: bytes) -> bytes | None:
    master = _master()
    if master is None:
        return None
    from cryptography.hazmat.primitives import hashes
    from cryptography.hazmat.primitives.kdf.hkdf import HKDF
    return HKDF(algorithm=hashes.SHA256(), length=32, salt=b"gramsoul-at-rest-v1", info=info).derive(master)


def enabled() -> bool:
    return _master() is not None


def db_key_hex() -> str | None:
    """The raw SQLCipher key (hex), or None when the database is not encrypted."""
    k = _derive(b"database")
    return k.hex() if k else None


def _file_key() -> bytes | None:
    return _derive(b"files")


def is_sealed(blob: bytes) -> bool:
    return blob[:4] == MAGIC


def seal(data: bytes, name: str) -> bytes:
    """Encrypts the content of the file called ``name`` (or returns it as is without DATA_KEY)."""
    key = _file_key()
    if key is None:
        return data
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    nonce = os.urandom(_NONCE)
    return MAGIC + nonce + AESGCM(key).encrypt(nonce, data, MAGIC + name.encode())


def unseal(blob: bytes, name: str) -> bytes:
    """The content of the file called ``name``: decrypted, or as is if it was stored before encryption."""
    if not is_sealed(blob):
        return blob
    key = _file_key()
    if key is None:
        raise DataKeyError("this file is encrypted, but DATA_KEY is not set in deploy/.env")
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    return AESGCM(key).decrypt(blob[4:4 + _NONCE], blob[4 + _NONCE:], MAGIC + name.encode())


def write_sealed(path: str, data: bytes, name: str) -> None:
    """Writes atomically (a reader never sees half a file), readable by the server's user only."""
    tmp = path + ".tmp"
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as f:
        f.write(seal(data, name))
    os.replace(tmp, path)


def read_sealed(path: str, name: str) -> bytes:
    with open(path, "rb") as f:
        return unseal(f.read(), name)


def migrate_files(directory: str, suffix: str) -> int:
    """Encrypts in place the files stored before DATA_KEY was set (``<name><suffix>``, sealed under <name>)."""
    if not enabled():
        return 0
    n = 0
    try:
        names = os.listdir(directory)
    except OSError:
        return 0
    for fn in names:
        if not fn.endswith(suffix):
            continue
        path = os.path.join(directory, fn)
        try:
            with open(path, "rb") as f:
                blob = f.read()
            if is_sealed(blob):
                continue
            write_sealed(path, blob, fn[: -len(suffix)])
            n += 1
        except OSError as e:
            log.warning("could not encrypt %s: %s", fn, e)
    if n:
        log.info("encrypted %d stored files in %s", n, directory)
    return n
